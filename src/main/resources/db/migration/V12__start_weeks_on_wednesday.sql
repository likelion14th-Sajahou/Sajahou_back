-- 주차 시작을 월요일에서 수요일(세션 날)로 바꾼다.
-- 세션은 모든 파트가 수요일이고, 세션 회고 마감은 일요일(기획·디자인·백엔드)~화요일(프론트)이다.
-- 월요일에 주차가 넘어가면 프론트 세션 회고가 마감 전에 '이번 주 회고' 화면에서 빠지고,
-- 월·화에는 아직 하지 않은 다음 세션이 이번 주로 보였다.
-- 수요일 시작이면 세션 날부터 다음 화요일까지가 한 주라 모든 파트의 마감이 그 주 안에 들어간다.
-- 현재 주차는 WeekService가 start_date로 정하므로 코드는 그대로 둔다.
-- 마감 일시(week_part_schedule)는 일시로 따로 저장돼 있어 바꾸지 않는다.
-- 월요일인 시작일만 옮긴다 (DAYOFWEEK: 1=일, 2=월).
UPDATE week
SET start_date = DATE_ADD(start_date, INTERVAL 2 DAY)
WHERE DAYOFWEEK(start_date) = 2;
